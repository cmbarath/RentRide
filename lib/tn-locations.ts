// Helper to flatten all active hubs across Tamil Nadu
export function getAllTNHubs(): TNHubLocation[] {
  return TN_CITIES.flatMap((city) => city.hubs).filter((hub) => hub.isActive);
}

// Find hub by ID
export function getTNHubById(hubId: string): TNHubLocation | undefined {
  return getAllTNHubs().find((h) => h.id === hubId);
}

